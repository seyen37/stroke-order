//: 顏文字近似寬度（mm）：字高 × 字數 × 係數（混寬字元的經驗值）。
export function approxWidthMm(text, sizeMm) {
  return [...String(text ?? '')].length * sizeMm * 0.62;
}

//: 超出框寬時要用的 textLength 擠壓值；放得下回 null（不擠壓）。
export function fitTextLength(text, sizeMm, boxW) {
  const natural = approxWidthMm(text, sizeMm);
  if (natural <= boxW) return null;
  return Math.max(boxW * 0.96, 1);
}
